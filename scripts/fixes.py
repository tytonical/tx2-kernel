#!/usr/bin/env python3
"""List the fixes applied to this tree, as Markdown or as an OpenVEX document.

Usage:
  scripts/fixes.py md   [--range A..B] > FIXES.md
  scripts/fixes.py vex  [--range A..B] --version V [--commit SHA] > fixes.openvex.json

Fixes are read from commit trailers between the pristine NVIDIA tarball import and HEAD:
  CVE: <id>               backport that fixes <id>
  Related-to: <id>        follow-up or correction to the backport for <id>
  Mitigates: <id>         local change that makes the code for <id> unreachable in this build
  Prerequisite-for: ...   upstream prerequisite of a later backport
  Backported-from: <sha>  stable commit used as the base of the port
and the "commit <sha> upstream." line. Commits with an upstream line but none of the CVE
trailers are listed as hardening fixes. CI publishes both outputs with each build; they are not
committed.

The VEX also includes docs/cve-baseline.tsv, a scan result for this tree's configuration:
  not_compiled   the affected source files are not compiled in this configuration
  fixed_in_base  already fixed in the NVIDIA L4T R32.7.6 sources this tree starts from
The VEX states only facts about this build. It makes no claim about CVEs whose code is
compiled and not fixed here: whether those matter depends on how the kernel is used.
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 'l4t-r32.7.6-tarball'
CVE_RE = r'CVE-\d{4}-\d+'


def git(*args):
    return subprocess.run(['git', '-C', TOP] + list(args), capture_output=True, text=True,
                          check=True).stdout


def commits(rev_range):
    out = git('log', '--reverse', '--no-merges', '--format=%H%x1f%s%x1f%B%x1e', rev_range)
    for rec in out.split('\x1e'):
        rec = rec.strip('\n')
        if not rec:
            continue
        sha, subject, body = rec.split('\x1f', 2)
        c = {'sha': sha, 'subject': subject, 'cve': [], 'related': [], 'mitigates': [],
             'prereq': False, 'stable': None, 'upstream': None}
        for line in body.splitlines():
            m = re.match(r'commit ([0-9a-f]{40}) upstream\.$', line.strip())
            if m:
                c['upstream'] = m.group(1)
            for key, field in (('CVE', 'cve'), ('Related-to', 'related'), ('Mitigates', 'mitigates')):
                m = re.match(key + r':\s*(.*)$', line)
                if m:
                    c[field] += re.findall(CVE_RE, m.group(1))
            if line.startswith('Prerequisite-for:'):
                c['prereq'] = True
            m = re.match(r'Backported-from:\s*([0-9a-f]{40})', line)
            if m:
                c['stable'] = m.group(1)
        yield c


def collect(rev_range):
    fixes, followups, mitig, prereqs, hardening, local = {}, {}, {}, [], [], []
    for c in commits(rev_range):
        for cve in c['cve']:
            fixes.setdefault(cve, []).append(c)
        for cve in c['related']:
            followups.setdefault(cve, []).append(c)
        for cve in c['mitigates']:
            mitig.setdefault(cve, []).append(c)
        if c['cve'] or c['related'] or c['mitigates']:
            continue
        if c['prereq']:
            prereqs.append(c)
        elif c['upstream']:
            hardening.append(c)
        else:
            local.append(c)
    return fixes, followups, mitig, prereqs, hardening, local


def cve_key(cve):
    return tuple(int(x) for x in cve.split('-')[1:])


def short(sha):
    return sha[:12] if sha else ''


def markdown(rev_range):
    fixes, followups, mitig, prereqs, hardening, local = collect(rev_range)
    out = ['# Fixes applied to this tree', '',
           f'Generated by `scripts/fixes.py md` from the commit trailers in `{rev_range}`. '
           'Do not edit by hand.', '',
           f'- {len(fixes)} CVEs fixed by backports ({sum(len(v) for v in fixes.values())} commits, '
           f'{sum(len(v) for v in followups.values())} follow-up commits)',
           f'- {len(mitig)} CVEs whose vulnerable code is made unreachable by a local change',
           f'- {len(prereqs)} upstream prerequisites, {len(hardening)} other upstream fixes, '
           f'{len(local)} local build and maintenance changes', '',
           '## CVE fixes', '',
           '| CVE | Commit | Subject | Upstream | Stable base | Follow-ups |',
           '|---|---|---|---|---|---|']
    for cve in sorted(fixes, key=cve_key):
        for c in fixes[cve]:
            fu = ', '.join(short(f['sha']) for f in followups.get(cve, []))
            out.append(f"| {cve} | {short(c['sha'])} | {c['subject']} | {short(c['upstream'])} "
                       f"| {short(c['stable'])} | {fu} |")
    orphans = sorted(set(followups) - set(fixes), key=cve_key)
    if orphans:
        out += ['', '## Follow-ups to CVE fixes inherited from the base tree', '',
                '| CVE | Commit | Subject | Upstream |', '|---|---|---|---|']
        for cve in orphans:
            for c in followups[cve]:
                out.append(f"| {cve} | {short(c['sha'])} | {c['subject']} | {short(c['upstream'])} |")
    out += ['', '## Local changes that make vulnerable code unreachable', '',
            'Not upstream fixes: these refuse or remove the affected feature in this build.', '',
            '| CVE | Commit | Subject |', '|---|---|---|']
    for cve in sorted(mitig, key=cve_key):
        for c in mitig[cve]:
            out.append(f"| {cve} | {short(c['sha'])} | {c['subject']} |")
    for title, rows in (('Upstream prerequisites of later backports', prereqs),
                        ('Other upstream fixes (no CVE)', hardening)):
        out += ['', f'## {title}', '', '| Commit | Subject | Upstream |', '|---|---|---|']
        out += [f"| {short(c['sha'])} | {c['subject']} | {short(c['upstream'])} |" for c in rows]
    out += ['', '## Local build and maintenance changes', '', '| Commit | Subject |', '|---|---|']
    out += [f"| {short(c['sha'])} | {c['subject']} |" for c in local]
    return '\n'.join(out) + '\n'


def baseline():
    path = os.path.join(TOP, 'docs', 'cve-baseline.tsv')
    rows = {}
    if os.path.exists(path):
        for line in open(path):
            if line.startswith('#') or not line.strip():
                continue
            cve, status, detail = (line.rstrip('\n').split('\t') + [''])[:3]
            rows[cve] = (status, detail)
    return rows


def vex(rev_range, version, commit):
    fixes, followups, mitig, _, _, _ = collect(rev_range)
    product = f'pkg:generic/tx2nx-kernel@{version}'
    if commit:
        product += f'?vcs_commit={commit}'
    stmts = []

    def stmt(cve, **kw):
        stmts.append(dict({'vulnerability': {'name': cve}, 'products': [{'@id': product}]}, **kw))

    done = set()
    for cve in sorted(fixes, key=cve_key):
        notes = 'Fixed by commit(s) ' + ', '.join(c['sha'] for c in fixes[cve])
        if cve in followups:
            notes += '; follow-up commit(s) ' + ', '.join(c['sha'] for c in followups[cve])
        stmt(cve, status='fixed', status_notes=notes + ' in this tree.')
        done.add(cve)
    for cve in sorted(set(mitig) - done, key=cve_key):
        stmt(cve, status='not_affected', justification='vulnerable_code_not_in_execute_path',
             impact_statement='The affected feature is refused or removed in this build by commit(s) '
             + ', '.join(c['sha'] for c in mitig[cve]) + '.')
        done.add(cve)
    for cve, (status, detail) in sorted(baseline().items(), key=lambda kv: cve_key(kv[0])):
        if cve in done:
            continue
        if status == 'not_compiled':
            stmt(cve, status='not_affected', justification='vulnerable_code_not_present',
                 impact_statement='None of the affected source files are compiled in this '
                 'configuration (' + detail + ').')
        elif status == 'fixed_in_base':
            stmt(cve, status='fixed', status_notes='Already fixed in the NVIDIA L4T R32.7.6 sources '
                 'this tree starts from. ' + detail)
        else:
            sys.exit(f'docs/cve-baseline.tsv: unknown status {status!r} for {cve}')
    return {
        '@context': 'https://openvex.dev/ns/v0.2.0',
        '@id': f'{product}#fixes',
        'author': 'tx2nx-kernel maintainers',
        'timestamp': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'version': 1,
        'tooling': 'scripts/fixes.py vex (commit trailers + docs/cve-baseline.tsv)',
        'statements': stmts,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('format', choices=['md', 'vex'])
    ap.add_argument('--range', default=BASE + '..HEAD')
    ap.add_argument('--version', help='release name, e.g. 4.9.337-tyton-1 (vex only)')
    ap.add_argument('--commit', help='commit the build is from (vex only)')
    a = ap.parse_args()
    if a.format == 'md':
        sys.stdout.write(markdown(a.range))
    else:
        if not a.version:
            ap.error('vex needs --version')
        json.dump(vex(a.range, a.version, a.commit), sys.stdout, indent=1)
        sys.stdout.write('\n')


if __name__ == '__main__':
    main()
